#!/usr/bin/env python3
"""Write docs/gui/GALLERY.md: every screenshot in docs/gui, in file-name
order, full width with its caption from the table in docs/gui/README.md.

Run after the screenshot tour or after editing the README's captions:

    scripts/make-gui-gallery.py
"""

import re
from pathlib import Path

GUI = Path(__file__).resolve().parent.parent / "docs" / "gui"

# | [03-idea-inbox-grid](03-idea-inbox-grid.png) | caption |
ROW = re.compile(r"^\|\s*\[([^\]]+)\]\(([^)]+\.png)\)\s*\|\s*(.*?)\s*\|\s*$")


def captions():
    out = {}
    for line in (GUI / "README.md").read_text().splitlines():
        m = ROW.match(line)
        if m:
            out[m.group(2)] = m.group(3)
    return out


def main():
    caps = captions()
    shots = sorted(p.name for p in GUI.glob("*.png"))
    lines = [
        "# IncreArt GUI gallery",
        "",
        "Every screenshot in order, full size. Generated by",
        "`scripts/make-gui-gallery.py` from the captions in the",
        "[screens table](README.md); don't edit by hand.",
        "",
    ]
    for name in shots:
        stem = name.removesuffix(".png")
        lines += [f"## {stem}", ""]
        if name in caps:
            lines += [caps[name], ""]
        lines += [f"![{stem}]({name})", ""]
    (GUI / "GALLERY.md").write_text("\n".join(lines))
    missing = [n for n in shots if n not in caps]
    print(f"{len(shots)} screenshots, {len(missing)} without a caption")
    for n in missing:
        print(f"  no caption: {n}")


if __name__ == "__main__":
    main()
